/// 1:1: `getSampleData()` — build the Uint8List sample buffer.
Uint8List _getSampleData() {
  final int charCode = 'd'.codeUnitAt(0);
  final Uint8List result = Uint8List(
      Constants.SAMPLED_CHAR_HEIGHT *
          Constants.SAMPLED_CHAR_WIDTH *
          Constants.RGBA_CHANNELS_CNT *
          Constants.CHAR_COUNT);
  for (int i = 0; i < result.length; i++) {
    result[i] = 0;
  }

  final int rowWidth = Constants.SAMPLED_CHAR_WIDTH *
      Constants.RGBA_CHANNELS_CNT *
      Constants.CHAR_COUNT;
  final int chIndex = charCode - Constants.START_CH_CODE;

  int globalOutputOffset = chIndex *
      Constants.SAMPLED_CHAR_WIDTH *
      Constants.RGBA_CHANNELS_CNT;
  int inputOffset = 0;
  for (int i = 0; i < Constants.SAMPLED_CHAR_HEIGHT; i++) {
    int outputOffset = globalOutputOffset;
    for (int j = 0; j < Constants.SAMPLED_CHAR_WIDTH; j++) {
      for (int channel = 0; channel < Constants.RGBA_CHANNELS_CNT; channel++) {
        result[outputOffset] = _sampleD[inputOffset];
        inputOffset++;
        outputOffset++;
      }
    }
    globalOutputOffset += rowWidth;
  }

  return result;
}

/// 1:1: `createFakeImageData(width, height)` -> MinimapImageData carrier.
MinimapImageData _createFakeImageData(int width, int height) {
  return MinimapImageData(
      width, height, Uint8List(width * height * Constants.RGBA_CHANNELS_CNT));
}

/// 1:1: `test('letter d @ 2x')`
void testLetterD2x() {
  final Uint8List sampleData = _getSampleData();
  final Uint8List source = Uint8List.fromList(sampleData);
  final renderer = MinimapCharRendererFactory.createFromSampleData(source, 2);

  final RGBA8 background = RGBA8(0, 0, 0, 255);
  final RGBA8 color = RGBA8(255, 255, 255, 255);
  final MinimapImageData imageData = _createFakeImageData(
      Constants.BASE_CHAR_WIDTH * 2, Constants.BASE_CHAR_HEIGHT * 2);
  for (int i = 0, len = imageData.data.length ~/ 4; i < len; i++) {
    imageData.data[4 * i + 0] = background.r.toInt();
    imageData.data[4 * i + 1] = background.g.toInt();
    imageData.data[4 * i + 2] = background.b.toInt();
    imageData.data[4 * i + 3] = 255;
  }
  renderer.renderChar(imageData, 0, 0, 'd'.codeUnitAt(0), color, 255,
      background, 255, 2, false, false);

  final List<int> expected = <int>[
      0x2D, 0x2D, 0x2D, 0xFF, 0xAC, 0xAC, 0xAC, 0xFF,
      0xC6, 0xC6, 0xC6, 0xFF, 0xC8, 0xC8, 0xC8, 0xFF,
      0xC0, 0xC0, 0xC0, 0xFF, 0xCB, 0xCB, 0xCB, 0xFF,
      0x00, 0x00, 0x00, 0xFF, 0x00, 0x00, 0x00, 0xFF,
  ];
  for (int i = 0; i < imageData.data.length; i++) {
    assert(imageData.data[i] == expected[i],
        'byte $i: ${imageData.data[i]} != ${expected[i]}');
  }
}

